"""Gaussian beam-splitter readout of hidden two-pair coherence.

The interaction is off during the readout. Each selected spin-resolved channel
is mixed by the number-conserving Gaussian unitary whose generator matches the
audit convention. For channels (p, h) and mixing angle alpha,

    K = exp(i phi) hop(p <- h) - exp(-i phi) hop(p <- h)^dagger,
    U = exp(alpha K).

alpha = pi/4 is the balanced splitter used in the closed formula. Broken-pair
states generated by U are retained. N_I is the particle number, after U, on the
four modes belonging to the two selected particle levels.

For a fixed-number seniority-zero state, the even-transfer twirl minus full
transfer-number dephasing has, at alpha = pi/4,

    Delta <exp(i chi N_I)> = Re(exp(4 i phi) <T>) / 8 * (exp(i chi) - 1)^4,
    Delta <(-1)^{N_I}> = 2 Re(exp(4 i phi) <T>).

T is the ordered product of the four fermion hops below, not an extra
interaction pulse. The first three raw moments of Delta p(N_I) vanish and the
fourth raw moment equals 3 Re(exp(4 i phi) <T>).
"""
from itertools import combinations
import numpy as np
from scipy.linalg import expm


def apply_hop_mask(mask, src, dst):
    """Move one fermion from src to dst. Returns (sign, new_mask) or None."""
    if (mask >> src) & 1 == 0:
        return None
    sign = -1 if (mask & ((1 << src) - 1)).bit_count() % 2 else 1
    cleared = mask ^ (1 << src)
    if (cleared >> dst) & 1:
        return None
    if (cleared & ((1 << dst) - 1)).bit_count() % 2:
        sign = -sign
    return sign, cleared | (1 << dst)


def paired_mode_mask(level_mask, levels):
    """Occupy both spin modes of every pair level set in level_mask."""
    mode = 0
    for level in levels:
        if level_mask & (1 << level):
            mode |= 3 << (2 * level)
    return mode


def transfer_channels(holes, particles):
    """Four disjoint spin channels, particle mode first, hole mode second."""
    channels = []
    for hole, particle in zip(holes, particles):
        for spin in (0, 1):
            channels.append((2 * particle + spin, 2 * hole + spin))
    return channels


def hop_product_element(level_mask, holes, particles, n_levels):
    """Matrix element of T on one seniority-zero configuration.

    T = hop(p2_down <- h2_down) @ hop(p2_up <- h2_up)
        @ hop(p1_down <- h1_down) @ hop(p1_up <- h1_up),
    so the rightmost hop acts first. Returns (sign, destination_level_mask)
    when all four hops are allowed, else None.
    """
    mask = paired_mode_mask(level_mask, range(n_levels))
    sign = 1
    for particle, hole in zip(particles, holes):
        for spin in (0, 1):
            step = apply_hop_mask(mask, 2 * hole + spin, 2 * particle + spin)
            if step is None:
                return None
            sign *= step[0]
            mask = step[1]
    destination = 0
    for level in range(n_levels):
        bit = 3 << (2 * level)
        if mask & bit == bit:
            destination |= 1 << level
        elif mask & bit:
            return None
    return sign, destination


def transfer_expectation(model, state, holes, particles):
    """<T> in the seniority-zero basis. T changes the selected levels by two pairs."""
    holes = tuple(int(x) for x in holes)
    particles = tuple(int(x) for x in particles)
    total = 0j
    for src, level_mask in enumerate(model.masks):
        step = hop_product_element(int(level_mask), holes, particles, model.L)
        if step is None:
            continue
        sign, destination = step
        total += np.conjugate(state[model.index[destination]]) * sign * state[src]
    return complex(total)


def _basis(n_particles):
    masks = [sum(1 << j for j in occ) for occ in combinations(range(8), n_particles)]
    return masks, {mask: i for i, mask in enumerate(masks)}


def beam_splitter_unitary(n_particles, phi, alpha):
    """Unitary on the fixed-particle sector of the eight selected modes.

    Local mode labels are h1, h2, p1, p2 in that order, two spins each:
    modes 0,1 belong to h1, 2,3 to h2, 4,5 to p1 and 6,7 to p2.
    """
    basis, index = _basis(n_particles)
    dim = len(basis)
    generator = np.zeros((dim, dim), complex)
    # Local levels (0, 1) are holes and (2, 3) are particles.
    for particle, hole in ((2, 0), (3, 1)):
        for spin in (0, 1):
            src = 2 * hole + spin
            dst = 2 * particle + spin
            for column, mask in enumerate(basis):
                step = apply_hop_mask(mask, src, dst)
                if step is None:
                    continue
                sign, dest = step
                row = index[dest]
                generator[row, column] += np.exp(1j * phi) * sign
                generator[column, row] += -np.exp(-1j * phi) * sign
    return expm(alpha * generator), basis


_UNITARY_CACHE = {}


def cached_unitary(n_particles, phi, alpha):
    key = (int(n_particles), round(float(phi), 12), round(float(alpha), 12))
    if key not in _UNITARY_CACHE:
        _UNITARY_CACHE[key] = beam_splitter_unitary(n_particles, phi, alpha)
    return _UNITARY_CACHE[key]


def _count_distribution(vector, basis):
    probability = np.abs(vector) ** 2
    upper = np.array([((mask >> 4) & 15).bit_count() for mask in basis], dtype=int)
    counts = np.bincount(upper, weights=probability.real, minlength=5).astype(float)
    return counts, upper


def twirl_count_difference(vector, basis, unitary):
    """Even-transfer mixture minus transfer-number dephasing, then U.

    The even state is the equal mixture of |psi> and |phase * psi>, with
    phase = exp(-i pi N_upper / 2). Dephasing removes coherences between
    different values of N_upper before U acts.
    """
    counts, upper = _count_distribution(unitary @ vector, basis)
    phase = np.exp(-1j * np.pi * upper / 2.0)
    even_counts = 0.5 * (counts + _count_distribution(unitary @ (phase * vector), basis)[0])
    dephased = np.zeros(5, float)
    evolved = unitary @ vector
    # Incoherent sum of the N_upper blocks of the input, evolved by the same U.
    for value in range(9):
        block = np.where(upper == value, vector, 0)
        if np.any(block):
            dephased += _count_distribution(unitary @ block, basis)[0]
    # The identity above double-uses `evolved` only as a shape check.
    del evolved
    delta = even_counts - dephased
    return {'even': even_counts, 'dephased': dephased, 'delta': delta,
            'raw': counts}


def local_active_groups(model, state, holes, particles):
    """Split a seniority-zero state into orthogonal spectator occupations.

    Non-selected levels are frozen by the beam splitter, so output counts add
    over those occupations. Each group is a state of the four selected levels.
    """
    selected = (int(holes[0]), int(holes[1]), int(particles[0]), int(particles[1]))
    if len(set(selected)) != 4:
        raise ValueError('interferometer ports must be four distinct pair levels')
    spectators = [level for level in range(model.L) if level not in selected]
    groups = {}
    for amplitude, level_mask in zip(state, model.masks):
        if amplitude == 0:
            continue
        spectator = 0
        active = 0
        for bit, level in enumerate(spectators):
            if int(level_mask) & (1 << level):
                spectator |= 1 << bit
        for bit, level in enumerate(selected):
            if int(level_mask) & (1 << level):
                active |= 1 << bit
        bucket = groups.setdefault(spectator, {})
        bucket[active] = bucket.get(active, 0j) + amplitude
    return groups


def interferometer_readout(model, state, holes, particles, phi, alpha=np.pi/4):
    """Exact N_I statistics after the Gaussian splitter.

    `raw` is the physical prepared state. `delta` is even-twirl minus transfer
    dephasing. Both include broken pairs created by the splitter.
    """
    holes = (int(holes[0]), int(holes[1]))
    particles = (int(particles[0]), int(particles[1]))
    raw = np.zeros(5, float)
    even = np.zeros(5, float)
    dephased = np.zeros(5, float)
    weight = 0.0
    for active in local_active_groups(model, state, holes, particles).values():
        n_pairs = next(iter(active)).bit_count()
        # Every configuration in one spectator sector has the same pair number.
        if any(mask.bit_count() != n_pairs for mask in active):
            raise RuntimeError('spectator sector changed the selected pair number')
        unitary, basis = cached_unitary(2 * n_pairs, phi, alpha)
        index = {mask: i for i, mask in enumerate(basis)}
        vector = np.zeros(len(basis), complex)
        for mask, amplitude in active.items():
            vector[index[paired_mode_mask(mask, range(4))]] = amplitude
        part = twirl_count_difference(vector, basis, unitary)
        raw += part['raw']
        even += part['even']
        dephased += part['dephased']
        weight += float(np.vdot(vector, vector).real)
    expectation = transfer_expectation(model, state, holes, particles)
    delta = even - dephased
    parity_sign = np.array([1., -1., 1., -1., 1.])
    predicted = formula_delta_counts(expectation, phi)
    numbers = np.arange(5)
    return {
        'phi': float(phi),
        'alpha': float(alpha),
        'holes': list(holes),
        'particles': list(particles),
        'T_real': float(expectation.real),
        'T_imag': float(expectation.imag),
        'sector_weight': weight,
        'raw_counts': raw,
        'even_counts': even,
        'dephased_counts': dephased,
        'delta_counts': delta,
        'raw_parity': float(raw @ parity_sign),
        'delta_parity': float(delta @ parity_sign),
        'formula_delta_counts': predicted,
        'formula_delta_parity': float(2 * np.real(np.exp(4j * phi) * expectation)) if np.isclose(alpha, np.pi / 4) else None,
        'formula_count_error': float(np.max(np.abs(delta - predicted))) if np.isclose(alpha, np.pi / 4) else None,
        'delta_moments_1_to_4': [float(delta @ numbers ** k) for k in range(1, 5)],
        'counts_are_probabilities': True,
    }


def formula_delta_counts(expectation, phi):
    """Balanced-splitter polynomial. Valid only for alpha = pi/4."""
    scale = np.real(np.exp(4j * phi) * expectation) / 8
    return scale * np.array([1., -4., 6., -4., 1.])


def characteristic_delta(expectation, phi, chi):
    """Closed form of Delta <exp(i chi N_I)> at alpha = pi/4."""
    return np.real(np.exp(4j * phi) * expectation) / 8 * (np.exp(1j * chi) - 1) ** 4


def orbit_parity_element(model, left, right, holes, particles, phi, alpha=np.pi/4):
    """<left|U† (-1)^{N_I} U|right> using stored symmetry-orbit vectors.

    The beam splitter does not change occupations outside the four selected
    levels, so distinct spectator sectors do not interfere. This equals the
    full-Gaussian group-average contraction when `left` and `right` are sector
    projections, and it is not a single-pair Wick contraction of two pure
    Gaussians.
    """
    holes = (int(holes[0]), int(holes[1]))
    particles = (int(particles[0]), int(particles[1]))
    left_groups = local_active_groups(model, left, holes, particles)
    right_groups = local_active_groups(model, right, holes, particles)
    total = 0j
    for key in set(left_groups) & set(right_groups):
        active = set(left_groups[key]) | set(right_groups[key])
        n_pairs = next(iter(active)).bit_count()
        unitary, basis = cached_unitary(2 * n_pairs, phi, alpha)
        index = {mask: i for i, mask in enumerate(basis)}
        left_vector = np.zeros(len(basis), complex)
        right_vector = np.zeros(len(basis), complex)
        for mask, amplitude in left_groups[key].items():
            left_vector[index[paired_mode_mask(mask, range(4))]] = amplitude
        for mask, amplitude in right_groups[key].items():
            right_vector[index[paired_mode_mask(mask, range(4))]] = amplitude
        upper = np.array([((mask >> 4) & 15).bit_count() for mask in basis])
        parity = np.where(upper % 2 == 0, 1.0, -1.0)
        evolved_right = unitary @ right_vector
        total += np.vdot(unitary @ left_vector, parity * evolved_right)
    return complex(total)


def count_errors(reference, other):
    """Total variation and parity error. Inputs are readout dictionaries."""
    ref = np.asarray(reference['delta_counts'], float)
    est = np.asarray(other['delta_counts'], float)
    variation = 0.5 * float(np.sum(np.abs(ref - est)))
    return {
        'delta_count_tv': variation,
        'delta_parity_error': float(other['delta_parity'] - reference['delta_parity']),
        'absolute_delta_parity_error': float(abs(other['delta_parity'] - reference['delta_parity'])),
        'raw_count_tv': 0.5 * float(np.sum(np.abs(np.asarray(reference['raw_counts']) - np.asarray(other['raw_counts'])))),
        'raw_parity_error': float(other['raw_parity'] - reference['raw_parity']),
    }
